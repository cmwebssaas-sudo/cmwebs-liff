// Extract the dependency closure of existing readers, without a second set of
// rental calculations. The result is plain JavaScript supported by workerd.
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { parse } from '../cloudflare/read-api/node_modules/acorn/dist/acorn.mjs';

const root = new URL('../', import.meta.url);
const entries = [
  'getWorkspaceLandlordHomeBootstrapByLineUid_',
  'getWorkspaceLandlordArrearsNativeByLineUid_',
  'getWorkspaceLandlordTenantsNativeByLineUid_',
  'getLandlordRoomCenterInitByLineUid_',
  'getLandlordPropertiesInitByLineUid_',
  'getLandlordRevenueDashboardByLineUid_'
];
const helpers=['landlordRoomWebsiteCoverTarget_','landlordRoomWebsitePhotosFromHtml_'];
// Runtime services replace only IO, schema mutation and identity resolution.
// C3 must supply verified access; these readers never resolve a client UID.
const adapters = [
  'workspaceLandlordResolveAccess_', 'runtimeSpreadsheet_',
  'runtimeSnapshotGetValues_', 'runtimeSnapshotGetContext_',
  'runtimeSnapshotSetContext_', 'workspaceLandlordLog_',
  'contractRequestLogAccess_', 'lmLogAccess_',
  'ensureV2ContractRequestsSheet_', 'lmEnsurePaymentReportSheet_',
  'lmEnsureTenantMessageSheet_', 'landlordInitiatedContractSchema_',
  'contractRequestResolveLandlordIdentity_', 'lmResolveLandlord_'
];
const excluded = new Set(adapters);
const definitions = new Map(), sources = new Map();
function walk(node, visit) {
  if (!node || typeof node !== 'object') return;
  if (node.type) visit(node);
  for (const value of Object.values(node)) {
    if (Array.isArray(value)) value.forEach(item => walk(item, visit));
    else if (value && typeof value === 'object') walk(value, visit);
  }
}
for (const file of (await readdir(new URL('apps-script/', root))).filter(f => f.endsWith('.js')).sort()) {
  const path = 'apps-script/'+file, source = await readFile(new URL(path, root),'utf8');
  sources.set(path, source);
  const ast = parse(source, {ecmaVersion:'latest',sourceType:'script'});
  for (const node of ast.body) {
    const names = node.type === 'FunctionDeclaration' ? [node.id.name]
      : node.type === 'VariableDeclaration' ? node.declarations.filter(d=>d.id.type==='Identifier').map(d=>d.id.name) : [];
    for (const name of names) {
      if (definitions.has(name)) throw new Error('Duplicate GAS symbol: '+name);
      definitions.set(name,{node,path,text:source.slice(node.start,node.end)});
    }
  }
}
const selected = new Map();
function add(name, parents=[]) {
  if (excluded.has(name) || selected.has(name)) return;
  const declaration = definitions.get(name);
  if (!declaration) throw new Error('Missing reader: '+name);
  // Refuse to accidentally include a mutation when a source reader changes.
  if (/\.(?:setValues?|appendRow|insertSheet|deleteRows?|setPropert(?:y|ies)|sendEmail|pushMessage)\s*\(/.test(declaration.text)) {
    throw new Error('Mutable dependency: '+[...parents,name].join(' -> '));
  }
  selected.set(name,declaration);
  const references = new Set();
  walk(declaration.node,node=>{if(node.type==='Identifier' && definitions.has(node.name) && node.name!==name) references.add(node.name);});
  for (const reference of references) add(reference,[...parents,name]);
}
[...entries,...helpers].forEach(name=>add(name));
const ordered = [...new Set([...selected.values()])].sort((a,b)=>a.path.localeCompare(b.path)||a.node.start-b.node.start);
const source = '// Generated by scripts/generate-read-calculator.mjs from the GAS reader dependency closure.\n'+
  '// No eval, Apps Script runtime, live Sheet writes or client identity resolution.\n'+
  'export function createReadCalculator(services) {\n'+
  'const { Date, Utilities, SpreadsheetApp, CacheService, UrlFetchApp, Logger, '+adapters.join(', ')+' } = services;\n'+
  ordered.map(d=>d.text).join('\n\n')+'\nreturn { '+[...entries,...helpers].join(', ')+' };\n}\n';
const manifest = {entries,helpers,adapters,functions:[...selected.keys()].filter(n=>definitions.get(n).node.type==='FunctionDeclaration').sort(),
  sources:Object.fromEntries([...new Set(ordered.map(d=>d.path))].sort().map(path=>[path,createHash('sha256').update(sources.get(path)).digest('hex')]))};
await writeFile(new URL('cloudflare/read-api/src/read-calculator.js',root),source);
await writeFile(new URL('cloudflare/read-api/read-source-manifest.json',root),JSON.stringify(manifest,null,2)+'\n');
console.log(JSON.stringify({functions:manifest.functions.length,sourceFiles:Object.keys(manifest.sources).length,bytes:Buffer.byteLength(source)}));
